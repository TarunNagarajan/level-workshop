test('authors edit three prompts, test a frozen snapshot and share findings deliberately', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const bootstrap = await signInOwner(page.request);
  await page.goto('/orchestration');
  if (!bootstrap.tutorialDone) {
    await page.getByRole('button', { name: 'Skip tour' }).waitFor();
    await page.getByRole('button', { name: 'Skip tour' }).click();
  }
  await page.getByRole('button', { name: 'New configuration' }).click();
  await expect(page.getByRole('heading', { name: 'Untitled orchestration' })).toBeVisible();
  await page.getByLabel('Configuration name').fill('Dispatch rehearsal');
  await page.getByLabel('Shared task').fill('Choose a route, a vehicle and a dispatch permit.');
  await page.getByLabel('Name for A').fill('Navigator');
  await page.getByLabel('System prompt for A').fill('You are the navigator. Explain the map evidence.');
  await page.getByLabel('Name for B').fill('Fleet officer');
  await page.getByLabel('System prompt for B').fill('You are the fleet officer. Explain vehicle capacity.');
  await page.getByLabel('Name for C').fill('Permit officer');
  await page.getByLabel('System prompt for C').fill('You are the permit officer. Explain the dispatch rules.');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByText('Saved configuration')).toBeVisible();
  await page.getByRole('button', { name: 'Orchestration', exact: true }).last().click();
  await expect(page.getByRole('button', { name: /Dispatch rehearsal/ })).toBeVisible();
  await page.getByRole('button', { name: /Dispatch rehearsal/ }).click();
  await page.getByLabel('Version note').fill('Initial specialist prompts');
  await page.getByRole('button', { name: 'Save version' }).click();
  await expect(page.getByLabel('Configuration to test').locator('option')).toHaveCount(2);
  await page.getByLabel('Test case').fill('Road 7 is closed and 20 people need a vehicle.');
  await page.getByRole('button', { name: 'Start test' }).click();
  await expect(page.getByRole('region', { name: 'Live test run' })).toBeVisible();
  await page.getByLabel('Question for A').fill('Which route works?');
  await page.getByRole('button', { name: 'Send to A' }).click();
  const laneA = page.locator('.orchestration-conversation').first();
  await expect(laneA.locator('.orchestration-message.assistant')).toHaveCount(1);
  await laneA.getByRole('button', { name: 'B', exact: true }).click();
  await expect(page.locator('.orchestration-board-item')).toHaveCount(1);
  await page.getByLabel('Question for B').fill('Which vehicle can carry them?');
  await page.getByRole('button', { name: 'Send to B' }).click();
  const laneB = page.locator('.orchestration-conversation').nth(1);
  await expect(laneB.locator('.orchestration-message.assistant')).toHaveCount(1);
  await laneB.getByRole('button', { name: 'Inspect context' }).click();
  await expect(page.getByRole('dialog').getByText(/Shared finding from A:/)).toBeVisible();
  await page.getByRole('dialog').getByLabel('Close dialog').click();
  await page.getByLabel('System prompt for A').fill('You are a revised navigator.');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await page.getByRole('button', { name: 'Start test' }).click();
  await expect(page.locator('.orchestration-history-row')).toHaveCount(2);
  await page.getByLabel('Compare with run').selectOption({ index: 1 });
  await expect(page.locator('.orchestration-comparison')).toContainText('You are a revised navigator.');
  await expect(page.locator('.orchestration-comparison')).toContainText('You are the navigator.');
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'verification/orchestration-desktop.png', animations: 'disabled', fullPage: true });
  await page.locator('.orchestration-history-row').last().click();
  await expect(page.getByLabel('Compare with run')).toHaveValue('');
  await expect(page.locator('.orchestration-comparison')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'verification/orchestration-mobile.png', animations: 'disabled', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('browser history does not silently discard an unsaved specialist prompt', async ({ page }) => {
  const bootstrap = await signInOwner(page.request);
  await page.goto('/orchestration');
  if (!bootstrap.tutorialDone) {
    await page.getByRole('button', { name: 'Skip tour' }).waitFor();
    await page.getByRole('button', { name: 'Skip tour' }).click();
  }
  await page.getByRole('button', { name: 'New configuration' }).click();
  await page.getByLabel('System prompt for A').fill('An unsaved specialist instruction.');
  page.once('dialog', dialog => dialog.dismiss());
  await page.goBack();
  await expect(page.getByLabel('System prompt for A')).toHaveValue('An unsaved specialist instruction.');
  page.once('dialog', dialog => dialog.accept());
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Orchestration lab' })).toBeVisible();
});

