import { test, expect, type Page } from '@playwright/test';

async function capture(page: Page, file: string) {
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: `verification/${file}`, fullPage: true, animations: 'disabled' });
}

test('passport desk supports physical inspection, questioning, evidence, design guide and blind mobile play', async ({ page, browser }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const account = { name: 'Workshop owner', email: 'ui-owner@example.test', password: 'ui-verification-password' };
  const setup = await page.request.post('/api/setup', { data: account });
  if (setup.status() === 409) await page.request.post('/api/login', { data: account });
  await page.request.put('/api/tutorial', { data: { result: 'skipped' } });
  await page.goto('/reference');
  await expect(page.getByRole('heading', { name: 'One last passenger', exact: true })).toBeVisible();
  for (const asset of ['background', 'passport-cover', 'open-book', 'stamp']) expect((await page.request.get(`/reference-assets/${asset}.webp`)).status()).toBe(200);
  const scripts = await page.locator('script[src]').evaluateAll(nodes => nodes.map(node => (node as HTMLScriptElement).src));
  for (const script of scripts) {
    const text = await (await page.request.get(script)).text();
    expect(text).not.toContain('Noah Vale');
    expect(text).not.toContain('brother’s passport');
    expect(text).not.toContain('brother’s ownership');
  }
  await capture(page, 'passport-intro.png');
  await page.getByRole('button', { name: 'Open the counter' }).click();
  await expect(page.getByText('INTERVIEW IN PROGRESS', { exact: false })).toBeVisible();
  const active = await (await page.request.get('/api/reference/active')).json();
  const grip = page.getByRole('button', { name: 'Move passport', exact: true });
  const rect = await grip.boundingBox();
  await page.mouse.move(rect!.x + rect!.width / 2, rect!.y + rect!.height / 2);
  await page.mouse.down(); await page.mouse.move(rect!.x + 95, rect!.y + 25, { steps: 8 }); await page.mouse.up();
  await expect(page.getByText('You move the passport.', { exact: true })).toBeVisible();
  const moved = await (await page.request.get(`/api/reference/rounds/${active.round.id}`)).json();
  expect(moved.state.positions.passport.x).toBeGreaterThan(active.state.positions.passport.x);
  await page.getByRole('button', { name: 'Inspect passport', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByText('ELIAS VALE', { exact: true })).toBeVisible();
  await capture(page, 'passport-identity-inspection.png');
  await dialog.getByRole('button', { name: 'Turn page', exact: true }).click();
  await expect(dialog.getByText('14 MAR 2024', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Inspect under UV' }).click();
  await expect(dialog.getByRole('button', { name: 'Warm light' })).toBeEnabled();
  await dialog.getByRole('button', { name: 'Present to passenger' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Request arrival card' }).click();
  await expect(page.getByRole('button', { name: 'Compare documents', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Compare documents', exact: true }).click();
  await expect(page.getByRole('dialog').getByText('N. Vale', { exact: true })).toBeVisible();
  await capture(page, 'passport-comparison.png');
  await page.getByRole('button', { name: 'Question about the documents' }).click();
  await page.getByLabel('Question the passenger', { exact: true }).fill('Whose passport is it?');
  await page.getByRole('button', { name: 'Send question' }).click();
  await expect(page.getByText('The passport belongs to my brother Elias. I am Noah.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Keep reply as evidence' }).click();
  await capture(page, 'passport-desk-desktop.png');
  await page.reload();
  await expect(page.getByText('The passport belongs to my brother Elias. I am Noah.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Remove reply from evidence' })).toBeVisible();
  const restored = await (await page.request.get(`/api/reference/rounds/${active.round.id}`)).json();
  expect(restored.state.positions.passport.x).toBe(moved.state.positions.passport.x);
  await page.getByRole('button', { name: 'Stamp and file the case' }).click();
  await page.getByLabel('Your finding', { exact: false }).fill('He identified his brother as the passport owner.');
  await page.getByRole('dialog').getByRole('checkbox').check();
  await page.getByRole('dialog').getByRole('button', { name: 'Stamp and file', exact: true }).click();
  await expect(page.getByText('Case filed.', { exact: true })).toBeVisible();
  const filed = await (await page.request.get(`/api/reference/rounds/${active.round.id}`)).json();
  expect(filed.state.evidence).toHaveLength(1); expect(filed.round.endedAt).toBeTruthy();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Explore the design' }).click();
  await expect(page.getByRole('heading', { name: 'How this scene was built.' })).toBeVisible();
  await page.getByRole('button', { name: /The second signature/ }).click();
  await expect(page.getByRole('heading', { name: 'The second signature' })).toBeVisible();
  await capture(page, 'passport-storyboard.png');
  await page.getByRole('tab', { name: 'Model context' }).click();
  await expect(page.locator('.protected-truth').getByText('The passenger is Noah Vale.', { exact: false })).toBeVisible();
  await expect(page.locator('.context-observations').getByText('Currently presented for questioning: passport, arrival card.', { exact: false })).toBeVisible();
  await page.getByRole('tab', { name: 'Build your own' }).click();
  await page.getByRole('button', { name: /Test, review and hand over/ }).click();
  await expect(page.getByRole('button', { name: 'Create my editable prompt draft' })).toBeVisible();
  await capture(page, 'passport-build-guide.png');
  await page.getByRole('button', { name: 'Share blind reference' }).click();
  const link = await page.getByLabel('Reference player link').inputValue();
  await page.getByLabel('Close dialog').click();
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const mobile = await mobileContext.newPage(); mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(link);
  await expect(mobile.getByRole('button', { name: 'Explore the design' })).toHaveCount(0);
  await mobile.getByRole('textbox', { name: /^Your name\b/ }).fill('Reference peer');
  await mobile.getByLabel(/Your submitted prompts, model replies, actions, findings and timing data/).check();
  await mobile.getByRole('button', { name: 'Open the counter' }).click();
  await mobile.getByRole('button', { name: 'Inspect passport', exact: true }).click();
  await expect(mobile.getByRole('dialog').getByText('RV 481 726', { exact: true })).toBeVisible();
  await mobile.getByRole('button', { name: 'Enlarge document' }).click();
  await expect(mobile.getByRole('button', { name: 'Fit document' })).toBeVisible();
  await mobile.getByRole('button', { name: 'Fit document' }).click();
  await capture(mobile, 'passport-inspection-mobile.png');
  await mobile.getByLabel('Close dialog').click();
  await mobile.getByRole('button', { name: 'Request arrival card' }).click();
  await mobile.getByLabel('Question the passenger', { exact: true }).fill('Explain the initials.');
  await mobile.getByRole('button', { name: 'Send question' }).click();
  await expect(mobile.getByText('The passport belongs to my brother Elias. I am Noah.', { exact: true })).toBeVisible();
  await mobile.reload();
  await expect(mobile.getByText('The passport belongs to my brother Elias. I am Noah.', { exact: true })).toBeVisible();
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await capture(mobile, 'passport-desk-mobile.png');
  await mobileContext.close();
  await page.getByRole('button', { name: 'Create my editable prompt draft' }).click();
  await expect(page.getByLabel('Level title')).toHaveValue('My passport-desk draft');
  await page.goto(`/attempts/${active.round.id}`);
  await expect(page.getByRole('checkbox', { name: 'Evidence' })).toBeChecked();
  await expect(page.getByText('Saved inspection trail', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
