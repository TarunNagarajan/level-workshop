import { test, expect, type Page } from '@playwright/test';

async function capture(page: Page, filename: string) {
  await page.evaluate(() => document.fonts.ready);
  if (await page.getByLabel('Dismiss notification').count()) await page.getByLabel('Dismiss notification').click();
  await page.screenshot({ path: `verification/${filename}`, fullPage: true, animations: 'disabled' });
}

test('authoring, blind play, version isolation, human review and responsive layouts', async ({ page, context, browser }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const needsSetup = (await (await page.request.get('/api/bootstrap')).json()).needsSetup;
  await page.goto('/');
  if (needsSetup) await page.getByLabel('Your name').fill('Workshop owner');
  await page.getByLabel('Email').fill('ui-owner@example.test');
  await page.getByLabel('Password').fill('ui-verification-password');
  await page.getByRole('button', { name: needsSetup ? 'Create account' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: /^Levels/ })).toBeVisible();
  if (await page.getByRole('button', { name: 'Skip tour' }).isVisible()) await page.getByRole('button', { name: 'Skip tour' }).click();
  await expect(page.getByRole('button', { name: /Riddle's diary/ })).toBeVisible();
  await capture(page, 'library-light.png');
  await page.getByRole('button', { name: /Riddle's diary/ }).click();
  await expect(page.getByLabel('Level title')).toHaveValue("Riddle's diary");
  await expect(page.getByRole('button', { name: 'Reveal protected truth' })).toBeVisible();
  await capture(page, 'editor-light.png');
  await page.getByRole('button', { name: 'Start test', exact: true }).click();
  await page.getByLabel('Message to target').fill('What did you tell Professor Dippet?');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.getByText('I expected the matter to be resolved before the night was over.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Hint', exact: true }).click();
  await expect(page.getByText('Separate when Riddle knew the accusation would be believed from when he knew it was true.')).toBeVisible();
  await page.getByRole('button', { name: 'Submit answer', exact: true }).click();
  await page.getByLabel('Your answer').fill('Riddle planned the accusation before the confrontation.');
  await page.getByRole('dialog').getByRole('button', { name: 'Submit answer' }).click();
  await expect(page.getByText('Answer submitted', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Blind test', exact: true }).click();
  const link = await page.getByLabel('Blind test link', { exact: true }).inputValue();
  await page.getByLabel('Close dialog').click();
  await page.getByLabel('Player briefing').fill('Question the diary. Determine whether the accusation was planned before the confrontation.');
  await page.getByRole('button', { name: 'Save version', exact: true }).click();
  await page.getByLabel('What changed?').fill('Shorter briefing for peer testing.');
  await page.getByRole('dialog').getByRole('button', { name: 'Save version' }).click();
  await expect(page.getByText('Version 02', { exact: true })).toBeVisible();
  const blindContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const blind = await blindContext.newPage();
  await blind.goto(link);
  await expect(blind.getByText('VERSION 01')).toBeVisible();
  await expect(blind.getByText('The diary contains a memory of the night Tom Riddle caught Hagrid hiding Aragog.', { exact: false })).toBeVisible();
  await expect(blind.getByLabel('Protected truth')).toHaveCount(0);
  const payload = await (await blind.request.get(`/api/play/${link.split('/').at(-1)}`)).json();
  expect(payload.level.secret).toBeUndefined();
  expect(payload.level.systemPrompt).toBeUndefined();
  await blind.getByLabel('Your name').fill('Peer tester');
  await blind.getByRole('button', { name: 'Start round' }).click();
  await blind.getByLabel('Message to target').fill('When did you promise to resolve the matter?');
  await blind.getByRole('button', { name: 'Send message' }).click();
  await expect(blind.getByText('I expected the matter to be resolved before the night was over.', { exact: false })).toBeVisible();
  await capture(blind, 'player-mobile.png');
  await blind.reload();
  await expect(blind.getByText('I expected the matter to be resolved before the night was over.', { exact: false })).toBeVisible();
  await blind.getByRole('button', { name: 'Submit answer' }).click();
  await blind.getByLabel('Your answer').fill('Riddle had already decided what to accuse Hagrid of.');
  await blind.getByRole('dialog').getByRole('button', { name: 'Submit answer' }).click();
  await expect(blind.getByText('Answer submitted', { exact: true })).toBeVisible();
  await blindContext.close();
  await page.getByRole('button', { name: 'Tests', exact: true }).click();
  await page.getByRole('button', { name: /Peer tester/ }).click();
  await page.getByLabel('Outcome').selectOption('partial');
  await page.getByLabel('Evidence', { exact: true }).check();
  await page.getByLabel('Reviewer notes').fill('Chronology emerged naturally, but the motive was not established.');
  await page.getByRole('button', { name: 'Save review' }).click();
  await expect(page.getByText('Partial', { exact: true })).toBeVisible();
  await capture(page, 'review-light.png');
  await page.getByRole('button', { name: 'Levels', exact: true }).click();
  await page.getByLabel('Use dark theme').click();
  await capture(page, 'library-dark.png');
  await page.getByRole('button', { name: /Riddle's diary/ }).click();
  await page.getByRole('button', { name: 'Start test', exact: true }).click();
  await page.getByLabel('Message to target').fill('What did you promise before the confrontation?');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.getByText('I expected the matter to be resolved before the night was over.', { exact: false })).toBeVisible();
  await page.reload();
  await expect(page.getByText('I expected the matter to be resolved before the night was over.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Branch from this reply' }).last().click();
  await expect(page.getByText('SAVED SESSION · BRANCH')).toBeVisible();
  await page.getByRole('button', { name: 'Replay a conversation' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Start replay' }).click();
  await expect(page.getByText('SAVED SESSION · REPLAY')).toBeVisible();
  await expect(page.getByText('Replay complete. Review the new responses.')).toBeVisible();
  await capture(page, 'editor-dark.png');
  await page.getByLabel('Use light theme').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await capture(page, 'editor-mobile.png');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('tab', { name: 'Instructions', exact: true }).click();
  await expect(page.getByLabel('System prompt')).toBeVisible();
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await expect(page.getByRole('button', { name: /Shorter briefing/ })).toBeVisible();
  await page.getByRole('button', { name: /Shorter briefing/ }).click();
  await expect(page.getByRole('heading', { name: 'Version 2', exact: true })).toBeVisible();
  await page.getByLabel('Close dialog').click();
  await page.getByRole('button', { name: 'Team', exact: true }).click();
  await page.getByRole('button', { name: 'Create workshop link' }).click();
  await expect(page.getByLabel('Invitation link', { exact: true })).toHaveValue(/\/enter\//);
  const invitation = await page.getByLabel('Invitation link', { exact: true }).inputValue();
  const author = await browser.newContext();
  const authorPage = await author.newPage();
  await authorPage.goto(invitation);
  await authorPage.getByLabel('Your name').fill('Workshop colleague');
  await expect(authorPage.getByLabel('Email', { exact: true })).toHaveCount(0);
  await expect(authorPage.getByLabel('Password', { exact: true })).toHaveCount(0);
  await authorPage.getByRole('button', { name: 'Enter workshop' }).click();
  await authorPage.getByRole('button', { name: 'Skip tour' }).click();
  await expect(authorPage.getByRole('heading', { name: 'Levels', exact: false })).toBeVisible();
  await authorPage.reload();
  await expect(authorPage.getByText('Workshop colleague', { exact: true })).toBeVisible();
  await author.close();
  expect(errors).toEqual([]);
});
